import type { Catalog } from '../i18n.js';

/*
 * Hebrew for the Sentinel screens (the Automations tab; see ../i18n.ts for how keys and holes work):
 * their own words, and the engine's sentences they draw (core/sentinel: schedules, steps, run
 * states, recipes' lines, tiles). A sentinel is "אוטומציה" (feminine); a run "הרצה"; a step "שלב";
 * a tile "אריח"; a dashboard "לוח מחוונים". Recipes' names and steps' names stay as they are: they
 * become the names of people's own sentinels.
 */

const DAYS: Readonly<Record<string, string>> = { Sun: 'ראשון', Mon: 'שני', Tue: 'שלישי', Wed: 'רביעי', Thu: 'חמישי', Fri: 'שישי', Sat: 'שבת' };
const MONTHS: Readonly<Record<string, string>> = { Jan: 'ינו׳', Feb: 'פבר׳', Mar: 'מרץ', Apr: 'אפר׳', May: 'מאי', Jun: 'יוני', Jul: 'יולי', Aug: 'אוג׳', Sep: 'ספט׳', Oct: 'אוק׳', Nov: 'נוב׳', Dec: 'דצמ׳' };

/** When a run was or runs next: weekdays and months with their times. */
const TIMES: Catalog = Object.fromEntries([
  ...Object.entries(DAYS).flatMap(([en, he]) => [
    [en, he],
    [`${en} {#0}:{#1}`, `יום ${he} {0}:{1}`],
    [`next ${en} {#0}:{#1}`, `הבאה ביום ${he} {0}:{1}`],
  ]),
  ...Object.entries(MONTHS).flatMap(([en, he]) => [
    [`${en} {#0} {#1}:{#2}`, `{0} ב${he} {1}:{2}`],
    [`${en} {#0}`, `{0} ב${he}`],
    [`next ${en} {#0}`, `הבאה ב־{0} ב${he}`],
  ]),
  // "Every week on Mon, Wed at 7:00": a hole for each day, each looked up on its own.
  ...[1, 2, 3, 4, 5, 6].map((n) => {
    const days = Array.from({ length: n }, (_, i) => `{${i}}`).join(', ');
    return [`Every week on ${days} at {#${n}}:{#${n + 1}}`, `כל שבוע ${n === 1 ? 'ביום' : 'בימים'} ${days} ב־{${n}}:{${n + 1}}`];
  }),
]);

